-- Banco da Biblioteca Aberta. Crie o banco biblioteca_aberta antes de executar.
DROP TABLE IF EXISTS public.emprestimos CASCADE;
DROP TABLE IF EXISTS public.livros CASCADE;
DROP TABLE IF EXISTS public.leitores CASCADE;
DROP TABLE IF EXISTS public.usuarios CASCADE;

CREATE TABLE public.usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(120) NOT NULL,
  email varchar(180) NOT NULL UNIQUE,
  senha_hash varchar(300) NOT NULL,
  perfil varchar(10) NOT NULL CHECK (perfil IN ('admin', 'leitor')),
  criado_em timestamptz NOT NULL DEFAULT now()
);

-- Um usuário pode possuir no máximo um cadastro de leitor (relacionamento 1:1).
CREATE TABLE public.leitores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL UNIQUE REFERENCES public.usuarios(id) ON DELETE CASCADE,
  telefone varchar(30),
  endereco varchar(200),
  cadastrado_em date NOT NULL DEFAULT CURRENT_DATE
);

-- Tabela independente do relacionamento de leitores e empréstimos.
CREATE TABLE public.livros (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo varchar(180) NOT NULL,
  autor varchar(140) NOT NULL,
  isbn varchar(20) UNIQUE,
  categoria varchar(80) NOT NULL,
  exemplares integer NOT NULL CHECK (exemplares > 0),
  capa_url text,
  sinopse text,
  criado_em timestamptz NOT NULL DEFAULT now()
);

-- Um leitor pode possuir vários empréstimos (relacionamento 1:N).
CREATE TABLE public.emprestimos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  leitor_id integer NOT NULL REFERENCES public.leitores(id) ON DELETE RESTRICT,
  livro_id integer NOT NULL REFERENCES public.livros(id) ON DELETE RESTRICT,
  emprestado_em date NOT NULL DEFAULT CURRENT_DATE,
  devolucao_prevista date NOT NULL,
  devolvido_em date,
  status varchar(12) NOT NULL CHECK (status IN ('ativo', 'devolvido')),
  CHECK (devolucao_prevista >= emprestado_em),
  CHECK ((status = 'ativo' AND devolvido_em IS NULL) OR (status = 'devolvido' AND devolvido_em IS NOT NULL))
);

CREATE INDEX emprestimos_livro_status_idx ON public.emprestimos(livro_id, status);
CREATE INDEX emprestimos_leitor_idx ON public.emprestimos(leitor_id);

